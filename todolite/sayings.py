# Bước nhảy nguyên tố cùng nhau với độ dài kho để các câu gần nhau trong bảng không rơi vào hai ngày liền nhau.
FIRST_STEP, SECOND_STEP = 137, 211


def _explained():
    return [Saying("Thành ngữ", text, FOLK, meaning) for text, meaning in IDIOMS] + [Saying("Cổ ngữ", text, FOLK, meaning) for text, meaning in MAXIMS]


def _plain():
    return ([Saying("Tục ngữ", text, FOLK, "") for text in PROVERBS] + [Saying("Ca dao", text, FOLK, "") for text in VERSES]
            + [Saying("Danh ngôn", text, source, "") for text, source in QUOTES])


def for_day(day):
    """Hai câu của một ngày: thành ngữ hoặc cổ ngữ kèm lời giải, rồi một câu tục ngữ, ca dao hoặc danh ngôn."""
    explained, plain = _explained(), _plain()
    number = day.toordinal()
    return explained[number * FIRST_STEP % len(explained)], plain[number * SECOND_STEP % len(plain)]
