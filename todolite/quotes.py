TOPIC_KEYS = tuple(key for key, *_ in TOPICS)


def chosen_topics(setting):
    """'folk,will' -> ('folk', 'will'). Chuỗi rỗng hay toàn khoá lạ thì lấy cả sáu chủ đề."""
    keys = set(setting.split(","))
    return tuple(key for key in TOPIC_KEYS if key in keys) or TOPIC_KEYS


def _order(count, seed):
    """Hoán vị cố định nhưng trông ngẫu nhiên: Fisher-Yates trên LCG 64 bit, không cần nạp module random."""
    order = list(range(count))
    state = (seed * 0x9E3779B97F4A7C15 + 1) & MASK
    for index in range(count - 1, 0, -1):
        state = (state * 6364136223846793005 + 1442695040888963407) & MASK
        pick = (state >> 33) % (index + 1)
        order[index], order[pick] = order[pick], order[index]
    return order


def _sequence(groups, cycle):
    """Thứ tự các câu trong một vòng. Mỗi lượt lấy một câu của từng chủ đề, thứ tự chủ đề xáo lại sau mỗi lượt: câu vẫn
    ngẫu nhiên, nhưng không có chuyện bốn ngày liền cùng một chủ đề."""
    queues = [[group[index] for index in _order(len(group), cycle * 31 + number)] for number, group in enumerate(groups)]
    sequence, turn = [], 0
    while any(queues):
        live = [queue for queue in queues if queue]
        sequence.extend(live[index].pop() for index in _order(len(live), cycle * 1009 + turn))
        turn += 1
    return sequence


def for_day(day, topics=TOPIC_KEYS):
    groups = [[Quote(key, label, text, author) for text, author in quotes] for key, _name, label, quotes in TOPICS if key in topics]
    cycle, position = divmod(day.toordinal(), sum(map(len, groups)))
    return _sequence(groups, cycle)[position]
